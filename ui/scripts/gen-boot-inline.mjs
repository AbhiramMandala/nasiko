#!/usr/bin/env node
/**
 * Keep the inline shell-boot script identical in every page head.
 *
 * The snippet has to be inline and synchronous: it puts the stored theme and the
 * rail width on `<html>` before first paint, and everything else that could set
 * them is a deferred module, so without it the shell paints in the OS theme with
 * a collapsed rail and then jumps. That means one copy per HTML page — 38 of
 * them — and hand-editing 38 copies of a one-liner is how they drift. It had
 * already started: the explanatory comment above it said three different things
 * in three groups of pages, and one page's copy had fallen a revision behind.
 *
 * So the snippet lives here, once, and this script writes it out. Behaviour is
 * unchanged from the copies it replaces — this is a de-duplication, not a change
 * to what boots.
 *
 *   node ui/scripts/gen-boot-inline.mjs            # rewrite every page
 *   node ui/scripts/gen-boot-inline.mjs --check    # fail if any page is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { glob } from 'node:fs/promises';
import { REPO, pageGlobs } from './editions.mjs';

/* Keys mirror the shell: the rail flag app-header.js persists, and the theme key
   theme.js owns. Minified by hand rather than by a tool, because it ships as
   source into every page. */
const SNIPPET =
  "<script>try{var d=document.documentElement,s=localStorage,t=s.getItem('app-theme');" +
  "if(t==='light'||t==='dark')d.dataset.theme=t;" +
  "if(s.getItem('app-rail-expanded-v2')==='true')" +
  "d.style.setProperty('--app-sidebar-width','var(--app-sidebar-width-expanded)')" +
  "}catch(e){}</script>";

const COMMENT = [
  '<!-- Generated by ui/scripts/gen-boot-inline.mjs — change the snippet there, not here.',
  '     Inline and synchronous on purpose: the stored theme and both rail widths have to',
  '     be on <html> before first paint. Every other script that could set them is a',
  '     deferred module, so without this the shell paints in the OS theme with',
  '     default-width rails and then jumps. -->',
];

/** The comment (if any) plus the boot script, as one replaceable block. */
const BLOCK_RE = /(?:[ \t]*<!--(?:(?!-->)[\s\S])*?-->\r?\n)?([ \t]*)<script>try\{(?:(?!<\/script>)[\s\S])*?app-theme(?:(?!<\/script>)[\s\S])*?<\/script>/;

const block = (indent) =>
  COMMENT.map((line, i) => (i === 0 ? indent + line : indent + line)).join('\n') + '\n' + indent + SNIPPET;

const checking = process.argv.includes('--check');
const stale = [];
let written = 0;
let scanned = 0;

// Which pages exist is each edition's own declaration (ui/<edition>/edition.json,
// `sources.pages`), not a list here: this script is published to the public repo,
// where naming a private edition's directory would both leak the private layout
// and glob a tree that is not there. See ui/scripts/editions.mjs.
for (const pattern of pageGlobs()) {
  for await (const entry of glob(pattern, { cwd: REPO })) {
    const rel = entry.replace(/\\/g, '/');
    if (rel.includes('/node_modules/') || rel.includes('/dist/')) continue;
    const path = resolve(REPO, rel);
    const source = readFileSync(path, 'utf8');
    const match = BLOCK_RE.exec(source);
    if (!match) continue;
    scanned++;
    const next = source.slice(0, match.index) + block(match[1]) + source.slice(match.index + match[0].length);
    if (next === source) continue;
    if (checking) stale.push(relative(REPO, path));
    else { writeFileSync(path, next); written++; }
  }
}

if (checking) {
  if (stale.length) {
    console.error(`gen-boot-inline: ${stale.length} of ${scanned} pages have a stale boot script:`);
    for (const f of stale) console.error(`  ${f}`);
    console.error('Run `node ui/scripts/gen-boot-inline.mjs` to update them.');
    process.exit(1);
  }
  console.log(`gen-boot-inline: ${scanned} pages up to date`);
} else {
  console.log(`gen-boot-inline: ${written} of ${scanned} pages rewritten`);
}
